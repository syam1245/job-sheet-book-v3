package com.example.jobsheetbook.util

import android.content.Context
import android.graphics.Canvas
import android.graphics.Color
import android.graphics.Paint
import android.graphics.pdf.PdfDocument
import com.example.jobsheetbook.domain.models.Job
import com.example.jobsheetbook.domain.models.JobStatus
import com.example.jobsheetbook.domain.models.WALK_IN_NAME
import java.io.File
import java.io.FileOutputStream
import java.text.SimpleDateFormat
import java.util.Locale
import java.util.Date

object PdfGenerator {
    suspend fun generateJobSheet(context: Context, job: Job): File? = kotlinx.coroutines.withContext(kotlinx.coroutines.Dispatchers.IO) {
        val pdfDocument = PdfDocument()
        val pageInfo = PdfDocument.PageInfo.Builder(595, 842, 1).create() // A4 size
        val page = pdfDocument.startPage(pageInfo)
        val canvas: Canvas = page.canvas
        val paint = Paint()

        // ── Header ──
        paint.textSize = 22f
        paint.isFakeBoldText = true
        canvas.drawText("JobSheetBook — Service Receipt", 50f, 55f, paint)

        paint.textSize = 10f
        paint.isFakeBoldText = false
        paint.color = Color.GRAY
        canvas.drawText("Admin Info Solution, Haripad", 50f, 72f, paint)
        paint.color = Color.BLACK

        // ── Divider ──
        paint.strokeWidth = 1f
        canvas.drawLine(50f, 82f, 545f, 82f, paint)

        // ── Job Info ──
        paint.textSize = 13f
        paint.isFakeBoldText = true
        canvas.drawText("JOB DETAILS", 50f, 105f, paint)

        paint.textSize = 12f
        paint.isFakeBoldText = false
        val dateStr = SimpleDateFormat("dd/MM/yyyy", Locale.getDefault()).format(Date(job.createdAt))
        val timeStr = SimpleDateFormat("hh:mm a", Locale.getDefault()).format(Date(job.createdAt))
        canvas.drawText("Job ID  :  ${job.displayId}", 50f, 125f, paint)
        canvas.drawText("Date    :  $dateStr    Time: $timeStr", 50f, 143f, paint)
        canvas.drawText("Status  :  ${job.rawStatus}", 50f, 161f, paint)

        // ── Customer ──
        paint.textSize = 13f
        paint.isFakeBoldText = true
        canvas.drawText("CUSTOMER", 50f, 190f, paint)

        paint.textSize = 12f
        paint.isFakeBoldText = false
        val displayName = job.customerName.ifBlank { WALK_IN_NAME }
        val displayPhone = PhoneNormalizer.formatForDisplay(job.customerPhone).ifBlank { "—" }
        canvas.drawText("Name    :  $displayName", 50f, 208f, paint)
        canvas.drawText("Phone   :  $displayPhone", 50f, 226f, paint)

        // ── Device ──
        paint.textSize = 13f
        paint.isFakeBoldText = true
        canvas.drawText("DEVICE", 50f, 255f, paint)

        paint.textSize = 12f
        paint.isFakeBoldText = false
        canvas.drawText("Type    :  ${job.itemType}  —  ${job.make} ${job.model}", 50f, 273f, paint)
        canvas.drawText("Serial  :  ${job.serialNumber.ifBlank { "N/A" }}", 50f, 291f, paint)

        // ── Remarks ──
        if (job.remarks.isNotBlank()) {
            paint.textSize = 13f
            paint.isFakeBoldText = true
            canvas.drawText("REMARKS", 50f, 320f, paint)
            paint.textSize = 12f
            paint.isFakeBoldText = false
            canvas.drawText(job.remarks.take(80), 50f, 338f, paint)
        }

        // ── QR Code ──
        QRCodeGenerator.generate("JOBSHEET_${job.jobId}", 100)?.let { qrBitmap ->
            canvas.drawBitmap(qrBitmap, 445f, 40f, paint)
        }

        // ── Footer ──
        paint.strokeWidth = 1f
        paint.color = Color.GRAY
        canvas.drawLine(50f, 800f, 545f, 800f, paint)
        paint.textSize = 10f
        canvas.drawText("This is an autogenerated receipt. Scan the QR code to view the job digitally.", 50f, 820f, paint)

        pdfDocument.finishPage(page)

        val outputDir = context.getExternalFilesDir(null)
        val file = File(outputDir, "Job_${job.jobId}.pdf")

        var out: FileOutputStream? = null
        try {
            out = FileOutputStream(file)
            pdfDocument.writeTo(out)
            file
        } catch (e: Exception) {
            e.printStackTrace()
            null
        } finally {
            pdfDocument.close()
            out?.close()
        }
    }

    suspend fun generateChipLevelReportPdf(context: Context, jobs: List<com.example.jobsheetbook.ui.viewmodel.ChipLevelJobItem>): File? = kotlinx.coroutines.withContext(kotlinx.coroutines.Dispatchers.IO) {
        val pdfDocument = PdfDocument()
        val pageInfo = PdfDocument.PageInfo.Builder(595, 842, 1).create() // A4 size
        var page = pdfDocument.startPage(pageInfo)
        var canvas: Canvas = page.canvas
        val paint = Paint()

        var y = 45f

        // ── Title Header ──
        paint.textSize = 18f
        paint.isFakeBoldText = true
        paint.color = Color.BLACK
        canvas.drawText("TechMech Payment Cross-Check Report", 40f, y, paint)
        y += 18f

        paint.textSize = 9f
        paint.isFakeBoldText = false
        paint.color = Color.DKGRAY
        val dateStr = SimpleDateFormat("dd MMM yyyy, hh:mm a", Locale.getDefault()).format(Date())
        canvas.drawText("Admin Info Solution, Haripad  —  Generated: $dateStr", 40f, y, paint)
        y += 12f

        paint.strokeWidth = 1.5f
        paint.color = Color.BLACK
        canvas.drawLine(40f, y, 555f, y, paint)
        y += 20f

        // ── Summary Cards Data ──
        val atTechMech = jobs.filter { it.job.status == JobStatus.CHIP_LEVEL || it.job.status == JobStatus.SENT_OUT }
        val delivered = jobs.filter { it.job.status == JobStatus.DELIVERED || it.job.status == JobStatus.RETURN }
        val stillWithShop = jobs.filter { it !in atTechMech && it !in delivered }

        val atTechMechSum = atTechMech.sumOf { it.info.tmCost }
        val deliveredSum = delivered.sumOf { it.info.tmCost }
        val stillWithShopSum = stillWithShop.sumOf { it.info.tmCost }
        val grandTotal = jobs.sumOf { it.info.tmCost }

        // Summary Boxes Row
        paint.textSize = 10f
        paint.isFakeBoldText = true
        paint.color = Color.rgb(179, 107, 0) // orange text
        canvas.drawText("AT TECHMECH: ${atTechMech.size} units (₹$atTechMechSum)", 40f, y, paint)

        paint.color = Color.rgb(26, 61, 42) // dark green text
        canvas.drawText("DELIVERED: ${delivered.size} units (₹$deliveredSum)", 230f, y, paint)

        paint.color = Color.DKGRAY
        canvas.drawText("WITH SHOP: ${stillWithShop.size} units (₹$stillWithShopSum)", 410f, y, paint)
        y += 20f

        paint.strokeWidth = 0.5f
        paint.color = Color.LTGRAY
        canvas.drawLine(40f, y, 555f, y, paint)
        y += 15f

        fun drawSectionTable(title: String, list: List<com.example.jobsheetbook.ui.viewmodel.ChipLevelJobItem>, titleColor: Int) {
            paint.textSize = 11f
            paint.isFakeBoldText = true
            paint.color = titleColor
            canvas.drawText(title, 40f, y, paint)
            y += 14f

            // Table Header
            paint.textSize = 8.5f
            paint.isFakeBoldText = true
            paint.color = Color.DKGRAY
            canvas.drawText("#", 40f, y, paint)
            canvas.drawText("TM JOB", 65f, y, paint)
            canvas.drawText("AI JOB", 115f, y, paint)
            canvas.drawText("CUSTOMER", 165f, y, paint)
            canvas.drawText("BRAND", 285f, y, paint)
            canvas.drawText("WORK", 355f, y, paint)
            canvas.drawText("DATE", 450f, y, paint)
            canvas.drawText("AMOUNT", 505f, y, paint)
            y += 6f

            paint.strokeWidth = 0.8f
            paint.color = Color.GRAY
            canvas.drawLine(40f, y, 555f, y, paint)
            y += 14f

            paint.isFakeBoldText = false
            paint.color = Color.BLACK
            paint.textSize = 8.5f

            if (list.isEmpty()) {
                paint.color = Color.GRAY
                canvas.drawText("No jobs in this section", 40f, y, paint)
                y += 16f
            } else {
                list.forEachIndexed { index, item ->
                    if (y > 790f) {
                        pdfDocument.finishPage(page)
                        val newPageInfo = PdfDocument.PageInfo.Builder(595, 842, pdfDocument.pages.size + 1).create()
                        page = pdfDocument.startPage(newPageInfo)
                        canvas = page.canvas
                        y = 40f
                    }

                    val jobDateStr = SimpleDateFormat("dd/MM/yy", Locale.getDefault()).format(Date(item.job.createdAt))
                    canvas.drawText("${index + 1}", 40f, y, paint)
                    canvas.drawText(item.info.tmJobId.ifBlank { "--" }, 65f, y, paint)
                    canvas.drawText(item.job.displayId, 115f, y, paint)
                    canvas.drawText(item.job.customerName.take(18), 165f, y, paint)
                    canvas.drawText("${item.job.make}".take(12), 285f, y, paint)
                    canvas.drawText(item.info.workDone.ifBlank { "--" }.take(16), 355f, y, paint)
                    canvas.drawText(jobDateStr, 450f, y, paint)
                    canvas.drawText("₹${item.info.tmCost}", 505f, y, paint)
                    y += 15f
                }
            }

            // Subtotal row
            val subtotal = list.sumOf { it.info.tmCost }
            paint.isFakeBoldText = true
            paint.textSize = 9.5f
            paint.color = Color.BLACK
            canvas.drawText("Subtotal (${list.size} jobs): ₹$subtotal", 380f, y, paint)
            y += 22f
        }

        drawSectionTable("⏳ At TechMech", atTechMech, Color.rgb(179, 107, 0))
        drawSectionTable("✓ Delivered to Customer", delivered, Color.rgb(26, 122, 63))
        drawSectionTable("🏬 Still with Shop", stillWithShop, Color.DKGRAY)

        // Grand Total Banner
        y += 10f
        if (y > 780f) {
            pdfDocument.finishPage(page)
            val newPageInfo = PdfDocument.PageInfo.Builder(595, 842, pdfDocument.pages.size + 1).create()
            page = pdfDocument.startPage(newPageInfo)
            canvas = page.canvas
            y = 40f
        }

        paint.color = Color.rgb(20, 20, 20)
        canvas.drawRect(40f, y, 555f, y + 32f, paint)

        paint.color = Color.WHITE
        paint.textSize = 11f
        paint.isFakeBoldText = true
        canvas.drawText("Total Pending Payment to TechMech", 55f, y + 20f, paint)
        canvas.drawText("₹$grandTotal", 470f, y + 20f, paint)

        pdfDocument.finishPage(page)

        val outputDir = context.getExternalFilesDir(null)
        val file = File(outputDir, "TechMech_CrossCheck_Report.pdf")

        var out: FileOutputStream? = null
        try {
            out = FileOutputStream(file)
            pdfDocument.writeTo(out)
            file
        } catch (e: Exception) {
            e.printStackTrace()
            null
        } finally {
            pdfDocument.close()
            out?.close()
        }
    }
}
